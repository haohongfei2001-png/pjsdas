import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const SHA_PATTERN = /^[0-9a-f]{7,64}$/i

function normalize(value) {
  const candidate = value?.trim()
  return candidate && SHA_PATTERN.test(candidate) ? candidate.toLowerCase() : undefined
}

function gitHead() {
  try {
    return normalize(execFileSync('git', ['rev-parse', 'HEAD'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }))
  } catch {
    return undefined
  }
}

const commitSha = normalize(process.env.PJSDAS_RELEASE_COMMIT_SHA)
  ?? normalize(process.env.VERCEL_GIT_COMMIT_SHA)
  ?? normalize(process.env.GITHUB_SHA)
  ?? normalize(process.env.WORKERS_CI_COMMIT_SHA)
  ?? gitHead()

const output = process.env.PJSDAS_RELEASE_IDENTITY_OUTPUT
  ? resolve(process.cwd(), process.env.PJSDAS_RELEASE_IDENTITY_OUTPUT)
  : new URL('../gateway/generatedReleaseIdentity.ts', import.meta.url)
const source = commitSha
  ? `// Generated by scripts/write-release-identity.mjs.\nexport const GENERATED_RELEASE_COMMIT_SHA = '${commitSha}' as const\n`
  : `// Generated by scripts/write-release-identity.mjs.\nexport const GENERATED_RELEASE_COMMIT_SHA: string | undefined = undefined\n`

writeFileSync(output, source, 'utf8')
console.log(`PJSDAS build release identity: ${commitSha ?? 'unbound'}`)
