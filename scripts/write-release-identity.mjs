import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { resolveCommitSha, resolveReleaseMetadata } from './release-metadata.mjs'

function gitHead() {
  try {
    const raw = execFileSync('git', ['rev-parse', 'HEAD'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim()
    return /^[0-9a-f]{7,64}$/i.test(raw) ? raw.toLowerCase() : undefined
  } catch {
    return undefined
  }
}

const commitSha = resolveCommitSha(process.env) ?? gitHead()
const metadata = resolveReleaseMetadata()

const output = process.env.PJSDAS_RELEASE_IDENTITY_OUTPUT
  ? resolve(process.cwd(), process.env.PJSDAS_RELEASE_IDENTITY_OUTPUT)
  : new URL('../gateway/generatedReleaseIdentity.ts', import.meta.url)

const source = [
  '// Generated by scripts/write-release-identity.mjs before production builds.',
  `export const GENERATED_RELEASE_COMMIT_SHA: string | undefined = ${commitSha ? JSON.stringify(commitSha) : 'undefined'}`,
  `export const GENERATED_PRODUCT_VERSION = ${JSON.stringify(metadata.productVersion)} as const`,
  `export const GENERATED_RELEASE_CHANNEL = ${JSON.stringify(metadata.releaseChannel)} as const`,
  `export const GENERATED_MCP_CONTRACT_HASH = ${JSON.stringify(metadata.mcpContractHash)} as const`,
  `export const GENERATED_MIGRATION_SET = ${JSON.stringify(metadata.migrationSet)} as const`,
  `export const GENERATED_MIGRATION_SET_HASH = ${JSON.stringify(metadata.migrationSetHash)} as const`,
  `export const GENERATED_SNAPSHOT_SCHEMA = ${JSON.stringify(metadata.snapshotSchema)} as const`,
  `export const GENERATED_SNAPSHOT_VERSION = ${metadata.snapshotVersion} as const`,
  '',
].join('\n')

writeFileSync(output, source, 'utf8')
console.log(`PJSDAS build release identity: ${commitSha ?? 'unbound'} · ${metadata.productVersion}`)
